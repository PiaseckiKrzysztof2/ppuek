print(2 + 2)    # Dodawanie
print(2 * 2)    # Mnożenie
print(2 ** 2)   # Potęgowanie
print(2 / 2)    # Dzielenie
print(5 // 2)   # Dzielenie całkowite
print(5 % 2)    # Reszta z dzielenia
print(5 > 2)    # Sprawdza czy 5 jest większe od 2
print(5 <= 5)   # Sprawdza czy 5 jest mniejsze lub równe 5